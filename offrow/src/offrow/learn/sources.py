def build_usu(
    root: Path,
    out_dir: Path,
    negatives_per_frame: int = 3,
    seed: int = 0,
    limit_frames: int | None = None,
) -> Manifest:
    """Examples from every annotated USU tile: the boxes, and clear ground between them."""
    dataset = datasets_mod.load_usu_corn_weeddb(Path(root))
    manifest = Manifest(Path(out_dir))
    rng = np.random.default_rng(seed)
    frames = dataset.frames[:limit_frames] if limit_frames else dataset.frames
    for frame in frames:
        image = frame.load()
        gsd_m = frame.gsd_mm / 1000.0
        group = frame.tile.source_id if frame.tile is not None else frame.image_path.stem
        split = split_for(f"usu:{group}")
        ref = str(frame.image_path.relative_to(Path(root)))
        boxes: list[tuple[float, float, float]] = []  # cx, cy, half span px
        for ann in frame.annotations:
            cx, cy = ann.centroid_px
            diameter = ann.equiv_diameter_m(frame.gsd_mm)
            span_m = object_span_m(diameter)
            span_px = int(round(span_m / gsd_m))
            chip, padded = cut_chip(image, cx, cy, span_px)
            eid = example_id(dataset.spec.key, ref, cx, cy, "weed")
            boxes.append((cx, cy, span_px / 2))
            _write(
                manifest,
                chip,
                Example(
                    id=eid,
                    source=dataset.spec.key,
                    source_ref=ref,
                    chip=f"{CHIP_DIR}/{eid}.png",
                    gsd_m=gsd_m,
                    span_m=span_px * gsd_m,
                    label="weed",
                    label_basis="annotated box (USU-Corn-WeedDB)",
                    group=group,
                    split=split,
                    crop=frame.crop,
                    growth_stage=frame.growth_stage,
                    species=ann.label,
                    diameter_m=diameter,
                    license=USU_LICENSE,
                    padded=padded,
                ),
            )
        for chip, cx, cy, basis, label in _negatives(image, gsd_m, boxes, negatives_per_frame, rng):
            eid = example_id(dataset.spec.key, ref, cx, cy, label)
            _write(
                manifest,
                chip,
                Example(
                    id=eid,
                    source=dataset.spec.key,
                    source_ref=ref,
                    chip=f"{CHIP_DIR}/{eid}.png",
                    gsd_m=gsd_m,
                    span_m=chip.shape[1] * gsd_m,
                    label=label,
                    label_basis=basis,
                    group=group,
                    split=split,
                    crop=frame.crop,
                    growth_stage=frame.growth_stage,
                    diameter_m=None,
                    license=USU_LICENSE,
                    padded=False,
                ),
            )
    manifest.write()
    return manifest


def _negatives(
    image: np.ndarray,
    gsd_m: float,
    boxes: list[tuple[float, float, float]],
    count: int,
    rng: np.random.Generator,
    attempts_per: int = 20,
) -> Iterable[tuple[np.ndarray, float, float, str, str]]:
    """Chips of clear ground in an exhaustively annotated frame, labelled by the mask."""
    h, w = image.shape[:2]
    span_px = int(round(object_span_m(DEFAULT_NEGATIVE_DIAMETER_M) / gsd_m))
    half = span_px / 2
    if span_px >= min(h, w):
        return
    clearance = NEGATIVE_CLEARANCE_SPANS * span_px
    found = 0
    for _ in range(count * attempts_per):
        if found >= count:
            break
        cx = rng.uniform(half, w - half)
        cy = rng.uniform(half, h - half)
        if any(math.hypot(cx - bx, cy - by) < clearance + bh for bx, by, bh in boxes):
            continue
        chip, _ = cut_chip(image, cx, cy, span_px)
        fraction = centre_vegetation_fraction(chip, gsd_m)
        if fraction >= CROP_VEGETATION_FRACTION:
            label, basis = (
                "crop",
                "derived: vegetation away from every annotated box (crop by mask)",
            )
        else:
            label, basis = (
                "other",
                "derived: ground away from every annotated box (not vegetation by mask)",
            )
        found += 1
        yield chip, cx, cy, basis, label


