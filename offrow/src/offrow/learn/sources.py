#: Weed sizes the synthetic source cycles through, so every diameter bin is
#: populated rather than only the 3 cm the flight spec defaults to.
SYNTH_WEED_DIAMETERS_M = (0.03, 0.06, 0.12, 0.25)
SYNTH_GSDS_MM = (5.5, 11.0, 22.0)


def scene_params_for(seed: int, acres: float = 0.25) -> synth_mod.SceneParams:
    """A varied scene per seed: size, confounders and row angle all move."""
    weed = SYNTH_WEED_DIAMETERS_M[seed % len(SYNTH_WEED_DIAMETERS_M)]
    return synth_mod.SceneParams(
        acres=acres,
        seed=seed,
        row_angle_deg=float((seed * 37) % 180),
        weed_diameter_m=weed,
        weed_diameter_max_m=max(0.10, weed * 2),
        shadows=seed % 2 == 0,
        wheel_tracks=seed % 3 == 0,
        wet_patches=seed % 4 == 0,
    )


def build_synth(
    out_dir: Path,
    seeds: Iterable[int] = range(24),
    gsds_mm: Iterable[float] = SYNTH_GSDS_MM,
    crop_per_scene: int = 40,
    other_per_scene: int = 30,
    weed_cap_per_scene: int = 120,
    acres: float = 0.25,
) -> Manifest:
    """Examples with exact truth, rendered natively at several resolutions."""
    manifest = Manifest(Path(out_dir))
    for seed in seeds:
        params = scene_params_for(seed, acres)
        scene = synth_mod.generate(params)
        group = f"synth:{seed}"
        split = split_for(group)
        rng = np.random.default_rng(seed)
        plant_xy = (
            np.concatenate([scene.crop_xy_m, scene.weed_xy_m])
            if len(scene.weed_xy_m)
            else scene.crop_xy_m
        )
        for gsd_mm in gsds_mm:
            gsd_m = gsd_mm / 1000.0
            image = synth_mod.render(scene, gsd_mm)
            ref = f"scene-{seed}@{gsd_mm:g}mm"
            weed_idx = np.arange(len(scene.weed_xy_m))
            if len(weed_idx) > weed_cap_per_scene:
                weed_idx = rng.choice(weed_idx, weed_cap_per_scene, replace=False)
            for i in weed_idx:
                x_m, y_m = scene.weed_xy_m[i]
                d = float(scene.weed_diameter_m[i])
                _synth_example(
                    manifest, image, gsd_m, x_m, y_m, d, "weed", ref, group, split, params
                )
            crop_idx = np.arange(len(scene.crop_xy_m))
            if len(crop_idx) > crop_per_scene:
                crop_idx = rng.choice(crop_idx, crop_per_scene, replace=False)
            for i in crop_idx:
                x_m, y_m = scene.crop_xy_m[i]
                d = float(scene.crop_diameter_m[i])
                _synth_example(
                    manifest, image, gsd_m, x_m, y_m, d, "crop", ref, group, split, params
                )
            for x_m, y_m in _clear_ground(
                scene.extent_m, plant_xy, other_per_scene, rng, clearance_m=0.20
            ):
                _synth_example(
                    manifest,
                    image,
                    gsd_m,
                    x_m,
                    y_m,
                    DEFAULT_NEGATIVE_DIAMETER_M,
                    "other",
                    ref,
                    group,
                    split,
                    params,
                )
    manifest.write()
    return manifest


def _synth_example(
    manifest, image, gsd_m, x_m, y_m, diameter_m, label, ref, group, split, params
) -> None:
    cx, cy = x_m / gsd_m, y_m / gsd_m
    span_px = int(round(object_span_m(diameter_m) / gsd_m))
    chip, padded = cut_chip(image, cx, cy, span_px)
    eid = example_id("synth", ref, cx, cy, label)
    basis = "synthetic truth" + (" (scene has shadows)" if params.shadows else "")
    _write(
        manifest,
        chip,
        Example(
            id=eid,
            source="synth",
            source_ref=ref,
            chip=f"{CHIP_DIR}/{eid}.png",
            gsd_m=gsd_m,
            span_m=span_px * gsd_m,
            label=label,
            label_basis=basis,
            group=group,
            split=split,
            crop="corn (synthetic)",
            growth_stage="V2-V6 (synthetic)",
            species="synthetic weed" if label == "weed" else None,
            diameter_m=diameter_m if label != "other" else None,
            license=SYNTH_LICENSE,
            padded=padded,
        ),
    )


def _clear_ground(
    extent_m,
    plant_xy: np.ndarray,
    count: int,
    rng: np.random.Generator,
    clearance_m: float,
    attempts_per: int = 30,
):
    """Points at least ``clearance_m`` from every plant, inside the field with a margin."""
    w, h = extent_m
    margin = object_span_m(DEFAULT_NEGATIVE_DIAMETER_M) / 2
    found = 0
    for _ in range(count * attempts_per):
        if found >= count:
            return
        x, y = rng.uniform(margin, w - margin), rng.uniform(margin, h - margin)
        if len(plant_xy) and np.min(np.hypot(plant_xy[:, 0] - x, plant_xy[:, 1] - y)) < clearance_m:
            continue
        found += 1
        yield x, y


