"""Where examples come from: a public set, a synthetic scene, an operator's verdicts.

Each builder turns one kind of source into a :class:`~offrow.learn.examples.Manifest`
with the label basis stated on every row. None of them pools with another; the
training loader reads every manifest under ``data/examples/`` and the scorecard
breaks results down by source, so a model that only learned synthetic corn
cannot hide behind a synthetic-heavy average.

**USU-Corn-WeedDB** labels three weed species and nothing else. Its annotated
tiles are exhaustively annotated (every weed in the tile has a box), so ground
that is far from every box is, by the dataset's own contract, not a weed. Those
chips are labelled by the repo's vegetation mask: mostly vegetation means the
corn, mostly not means soil. The basis says so, because a derived label is not
an annotated one.

**Synthetic scenes** carry exact truth: every crop plant, every weed and every
patch of bare soil is known. They are the only source that populates the
smallest diameter bin, which is the one the flight spec is about, and the only
one where shadows, wheel tracks and wet soil can be switched on to be learned
as "other".

**Operator verdicts** are the archive the scout already keeps
(``weed_observations`` and the ``weed-chips`` bucket). They are the only labels
from the imagery operators actually fly, and the only ones that come with the
scout's own chip framing. Few today; the point of the loop is that there will
be more.
"""

from __future__ import annotations

import json
import math
from collections.abc import Iterable
from dataclasses import replace
from pathlib import Path

import numpy as np

from offrow import datasets as datasets_mod
from offrow import synth as synth_mod
from offrow.learn.examples import (
    CHIP_DIR,
    DEFAULT_NEGATIVE_DIAMETER_M,
    Example,
    Manifest,
    centre_vegetation_fraction,
    cut_chip,
    example_id,
    load_chip,
    object_span_m,
    save_chip,
    split_for,
)

#: A negative chip's centre must be at least this far, in chip spans, from the
#: centre of every annotated box, so no labelled object leaks into it.
NEGATIVE_CLEARANCE_SPANS = 0.75

#: Centre vegetation fraction at or above which an unlabelled chip is "crop".
CROP_VEGETATION_FRACTION = 0.25

USU_LICENSE = "CC BY 4.0 (USU-Corn-WeedDB, Zenodo 20044178)"
SYNTH_LICENSE = "generated by offrow.synth; no external rights"
OPERATOR_LICENSE = "operator-owned; consent required before leaving the operator's account"


def _write(manifest: Manifest, chip: np.ndarray, example: Example) -> Example:
    save_chip(chip, manifest.chip_path(example))
    manifest.add(example)
    return example


