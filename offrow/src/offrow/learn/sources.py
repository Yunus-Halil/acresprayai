#: Columns pulled from weed_observations. The verdict is the label; the rest is provenance.
OBSERVATION_COLUMNS = (
    "id,user_id,field_id,scan_id,candidate_id,kind,verdict,verdict_source,species,crop,growth_stage,"
    "gsd_m,chip_gsd_m,chip_span_m,chip_path,area_m2,features,captured_at,pipeline_version,"
    "prediction,model_version,inference,finding_class,lat,lng"
)


def pull_verdicts(supabase_url: str, service_key: str, out_dir: Path) -> Path:
    """Export every observation with a verdict and a chip, plus the chips, to ``out_dir``.

    Needs the service role, because the archive is owner-scoped by RLS and this
    is a training export across every operator who has consented. Nothing here
    is called from the app; it runs on a machine that holds the key.
    """
    import requests

    out_dir = Path(out_dir)
    chips = out_dir / "raw"
    chips.mkdir(parents=True, exist_ok=True)
    headers = {"apikey": service_key, "Authorization": f"Bearer {service_key}"}
    rows: list[dict] = []
    offset = 0
    while True:
        r = requests.get(
            f"{supabase_url}/rest/v1/weed_observations",
            params={
                "select": OBSERVATION_COLUMNS,
                "verdict": "not.is.null",
                "chip_path": "not.is.null",
                "order": "created_at.asc",
                "offset": offset,
                "limit": 500,
            },
            headers=headers,
            timeout=60,
        )
        r.raise_for_status()
        page = r.json()
        rows.extend(page)
        if len(page) < 500:
            break
        offset += 500
    for row in rows:
        target = chips / f"{row['id']}.png"
        if target.exists():
            continue
        r = requests.get(
            f"{supabase_url}/storage/v1/object/weed-chips/{row['chip_path']}",
            headers=headers,
            timeout=60,
        )
        if r.ok:
            target.write_bytes(r.content)
        else:
            row["chip_missing"] = True
    export = out_dir / "observations.json"
    export.write_text(json.dumps(rows, indent=1))
    return export


def build_operator(export_dir: Path, out_dir: Path | None = None) -> Manifest:
    """Examples from an export written by :func:`pull_verdicts`."""
    export_dir = Path(export_dir)
    rows = json.loads((export_dir / "observations.json").read_text())
    manifest = Manifest(Path(out_dir) if out_dir else export_dir)
    for row in rows:
        raw = export_dir / "raw" / f"{row['id']}.png"
        if row.get("chip_missing") or not raw.exists() or not row.get("chip_span_m"):
            continue
        verdict = row.get("verdict")
        if verdict not in ("weed", "crop", "not_vegetation", "not_weed"):
            continue  # "unsure" teaches nothing
        image = load_chip(raw)
        png_px = max(image.shape[:2])
        span_m = float(row["chip_span_m"])
        gsd_m = span_m / png_px  # the stored PNG may be upscaled; its own GSD is span over pixels
        features = row.get("features") or {}
        diameter = features.get("equivDiameterM") if isinstance(features, dict) else None
        span_px = int(round(object_span_m(diameter or DEFAULT_NEGATIVE_DIAMETER_M) / gsd_m))
        chip, padded = cut_chip(image, image.shape[1] / 2, image.shape[0] / 2, min(span_px, png_px))
        if verdict == "weed":
            label, basis = "weed", "operator verdict: weed"
        elif verdict == "crop":
            label, basis = "crop", "operator verdict: crop"
        elif verdict == "not_vegetation":
            label, basis = "other", "operator verdict: not vegetation"
        else:
            veg = centre_vegetation_fraction(chip, gsd_m)
            label = "crop" if veg >= CROP_VEGETATION_FRACTION else "other"
            basis = f"operator verdict: not a weed; {label} by mask"
        group = f"field:{row.get('field_id') or row.get('user_id')}"
        eid = example_id("operator", row["id"], 0, 0, label)
        _write(
            manifest,
            chip,
            Example(
                id=eid,
                source="operator",
                source_ref=row["id"],
                chip=f"{CHIP_DIR}/{eid}.png",
                gsd_m=gsd_m,
                span_m=chip.shape[1] * gsd_m,
                label=label,
                label_basis=basis,
                group=group,
                split=split_for(group),
                crop=row.get("crop") or "",
                growth_stage=row.get("growth_stage") or "",
                species=row.get("species") if label == "weed" else None,
                diameter_m=diameter,
                license=OPERATOR_LICENSE,
                padded=padded,
            ),
        )
    manifest.write()
    return manifest


def relabel(manifest: Manifest, example_id_: str, label: str, basis: str) -> Manifest:
    """A reviewed correction. Returns a new manifest; the old file is untouched until written."""
    out = Manifest(manifest.directory)
    for e in manifest:
        out.add(replace(e, label=label, label_basis=basis) if e.id == example_id_ else e)
    return out
